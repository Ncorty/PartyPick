import type { Game, GameGenre, GameMode, GameProfile } from './index.js';

// Editorial PC session profiles, not exhaustive game/queue descriptions.
// Estimates include a small setup buffer; matches can run longer.
function profile(
  id: string,
  name: string,
  mode: GameMode,
  maxParty: number,
  estimatedMinutes: number,
  intensity: GameProfile['intensity'] = 'focused',
  teamSize?: number,
): GameProfile {
  return {
    id,
    name,
    mode,
    minParty: 1,
    maxParty,
    estimatedMinutes,
    intensity,
    allowsRandoms: teamSize !== undefined,
    ...(teamSize === undefined ? {} : { teamSize }),
  };
}
function game(
  id: string,
  name: string,
  genres: GameGenre[],
  freeToPlay: boolean,
  description: string,
  sourceUrl: string,
  profiles: GameProfile[],
): Game {
  return {
    id,
    name,
    genres,
    freeToPlay,
    description,
    sourceUrl,
    profiles,
    minPlayers: Math.min(...profiles.map((p) => p.minParty)),
    maxPlayers: Math.max(...profiles.map((p) => p.maxParty)),
    modes: [...new Set(profiles.map((p) => p.mode))],
    suggestedMinutes: Math.min(...profiles.map((p) => p.estimatedMinutes)),
  };
}
